"""
Keccak-p[1600] permutation and SHA-3 hash functions.

State model
-----------
The 1600-bit state is a 5x5 array of 64-bit lanes ``A[x][y]`` (x, y in 0..4),
each lane an ``int`` whose bit ``z`` is ``(lane >> z) & 1`` (z in 0..63), as in
FIPS 202.  Round constants and rotation offsets are the standard ones.

For the symmetry experiments we need *reduced-round* permutations, so
``keccak_p`` takes an explicit round count and starts from round 0 (the usual
cryptanalytic convention).  SHA-3 uses the full 24 rounds.

Only what the artifact needs is implemented; this is a readable reference, not
a fast one.
"""

from __future__ import annotations

MASK64 = (1 << 64) - 1

# Round constants of Keccak-f[1600] (FIPS 202, Table).
RC = [
    0x0000000000000001, 0x0000000000008082, 0x800000000000808A,
    0x8000000080008000, 0x000000000000808B, 0x0000000080000001,
    0x8000000080008081, 0x8000000000008009, 0x000000000000008A,
    0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
    0x000000008000808B, 0x800000000000008B, 0x8000000000008089,
    0x8000000000008003, 0x8000000000008002, 0x8000000000000080,
    0x000000000000800A, 0x800000008000000A, 0x8000000080008081,
    0x8000000000008080, 0x0000000080000001, 0x8000000080008008,
]


def _rho_offsets():
    """Rotation offsets rho[x][y] generated by the standard (x,y) walk."""
    offs = [[0] * 5 for _ in range(5)]
    x, y = 1, 0
    for t in range(24):
        offs[x][y] = ((t + 1) * (t + 2) // 2) % 64
        x, y = y, (2 * x + 3 * y) % 5
    return offs


RHO = _rho_offsets()


def rotl(v: int, n: int) -> int:
    n &= 63
    if n == 0:
        return v & MASK64
    return ((v << n) | (v >> (64 - n))) & MASK64


# ---------------------------------------------------------------------------
# Round function (split so chi / chi^{-1} can be used in isolation)
# ---------------------------------------------------------------------------

def theta(A):
    C = [A[x][0] ^ A[x][1] ^ A[x][2] ^ A[x][3] ^ A[x][4] for x in range(5)]
    D = [C[(x - 1) % 5] ^ rotl(C[(x + 1) % 5], 1) for x in range(5)]
    return [[A[x][y] ^ D[x] for y in range(5)] for x in range(5)]


def rho_pi(A):
    B = [[0] * 5 for _ in range(5)]
    for x in range(5):
        for y in range(5):
            B[y][(2 * x + 3 * y) % 5] = rotl(A[x][y], RHO[x][y])
    return B


def chi(A):
    return [[A[x][y] ^ ((~A[(x + 1) % 5][y]) & A[(x + 2) % 5][y]) & MASK64
             for y in range(5)] for x in range(5)]


def _build_chi5_inverse():
    """Inverse table for the 5-bit Keccak chi S-box (applied to one lane-row).

    chi on a row (bits a0..a4 on a circle): o_x = a_x ^ (~a_{x+1} & a_{x+2}).
    Only 32 inputs exist, so we invert by exhaustive table."""
    inv = [0] * 32
    for v in range(32):
        a = [(v >> x) & 1 for x in range(5)]
        o = [a[x] ^ ((1 - a[(x + 1) % 5]) & a[(x + 2) % 5]) for x in range(5)]
        ov = sum(o[x] << x for x in range(5))
        inv[ov] = v
    return inv


_CHI5_INV = _build_chi5_inverse()


def chi_inv(A):
    """Exact inverse of chi (each lane-row y and bit position z is an
    independent 5-bit S-box)."""
    out = [[0] * 5 for _ in range(5)]
    for y in range(5):
        for z in range(64):
            ov = sum(((A[x][y] >> z) & 1) << x for x in range(5))
            v = _CHI5_INV[ov]
            for x in range(5):
                out[x][y] |= ((v >> x) & 1) << z
    return out


def iota(A, rnd):
    A = [row[:] for row in A]
    A[0][0] ^= RC[rnd]
    return A


def keccak_round(A, rnd):
    return iota(chi(rho_pi(theta(A))), rnd)


def keccak_p(A, nrounds, start=0):
    """Apply ``nrounds`` Keccak-p rounds to lane array ``A`` (starting at round
    index ``start``).  Returns a new lane array."""
    A = [row[:] for row in A]
    for r in range(start, start + nrounds):
        A = keccak_round(A, r)
    return A


# ---------------------------------------------------------------------------
# Byte <-> lane packing and SHA-3 sponge (for KAT validation only)
# ---------------------------------------------------------------------------

def bytes_to_state(b: bytes):
    assert len(b) == 200
    A = [[0] * 5 for _ in range(5)]
    for x in range(5):
        for y in range(5):
            i = 8 * (x + 5 * y)
            A[x][y] = int.from_bytes(b[i:i + 8], "little")
    return A


def state_to_bytes(A) -> bytes:
    out = bytearray(200)
    for x in range(5):
        for y in range(5):
            i = 8 * (x + 5 * y)
            out[i:i + 8] = (A[x][y] & MASK64).to_bytes(8, "little")
    return bytes(out)


def _keccak_sponge(data: bytes, rate_bytes: int, out_len: int, dsbyte: int) -> bytes:
    state = bytearray(200)
    # Absorb with pad10*1 and domain-separation byte.
    msg = bytearray(data)
    msg.append(dsbyte)
    while len(msg) % rate_bytes != 0:
        msg.append(0x00)
    msg[-1] ^= 0x80
    for off in range(0, len(msg), rate_bytes):
        for i in range(rate_bytes):
            state[i] ^= msg[off + i]
        state = bytearray(state_to_bytes(keccak_p(bytes_to_state(bytes(state)), 24)))
    # Squeeze.
    out = bytearray()
    while len(out) < out_len:
        out.extend(state[:rate_bytes])
        if len(out) < out_len:
            state = bytearray(state_to_bytes(keccak_p(bytes_to_state(bytes(state)), 24)))
    return bytes(out[:out_len])


def sha3_224(m: bytes) -> bytes: return _keccak_sponge(m, 144, 28, 0x06)
def sha3_256(m: bytes) -> bytes: return _keccak_sponge(m, 136, 32, 0x06)
def sha3_384(m: bytes) -> bytes: return _keccak_sponge(m, 104, 48, 0x06)
def sha3_512(m: bytes) -> bytes: return _keccak_sponge(m, 72, 64, 0x06)
